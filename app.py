@app.route("/gps", methods=["POST"])
def receive_gps():
    data = request.get_json(silent=True)
    if not data:
        return jsonify({"error": "GPS data was not received."}), 400

    try:
        user_lat = float(data["latitude"])
        user_lon = float(data["longitude"])
        accuracy = float(data.get("accuracy", 0))

        if not all(map(math.isfinite, [user_lat, user_lon, accuracy])):
            raise ValueError()
        if not -90 <= user_lat <= 90:
            raise ValueError()
        if not -180 <= user_lon <= 180:
            raise ValueError()
        if accuracy < 0:
            raise ValueError()
    except (KeyError, TypeError, ValueError):
        return jsonify({"error": "Invalid GPS coordinates or accuracy."}), 400

    nearest = find_nearest_station(user_lat, user_lon)

    if nearest["nearby"]:
        message = (
            "You are within 0.5 km of " +
            nearest["nearest_station"] + " Metro Station."
        )
    else:
        message = (
            "No Green Line station is within 0.5 km. The nearest station is " +
            nearest["nearest_station"] + "."
        )

    response_data = {
        "status": "success",
        "latitude": user_lat,
        "longitude": user_lon,
        "gps_accuracy_m": round(accuracy, 1),
        "nearest_station": nearest["nearest_station"],
        "distance_km": nearest["distance_km"],
        "nearby": nearest["nearby"],
        "nearest_latitude": nearest["station_latitude"],
        "nearest_longitude": nearest["station_longitude"],
        "nearby_stations": nearest["nearby_stations"],
        "message": message
    }

    print(
        "GPS received:", user_lat, user_lon,
        "| Accuracy:", accuracy,
        "| Nearest:", nearest["nearest_station"],
        "| Distance:", nearest["distance_km"], "km"
    )
    print(
        "Station coordinates returned:",
        response_data["nearest_latitude"],
        response_data["nearest_longitude"]
    )
    return jsonify(response_data)

