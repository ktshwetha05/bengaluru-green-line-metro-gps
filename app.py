def find_nearest_station(user_lat, user_lon):
    nearest_station = None
    nearest_distance = float("inf")
    nearby_stations = []

    for _, station in stations.iterrows():
        station_lat = float(station["latitude"])
        station_lon = float(station["longitude"])
        distance = haversine(user_lat, user_lon, station_lat, station_lon)

        if distance < nearest_distance:
            nearest_distance = distance
            nearest_station = station

        if distance <= 0.5:
            nearby_stations.append({
                "station_name": str(station["station_name"]),
                "distance_km": round(distance, 3),
                "latitude": station_lat,
                "longitude": station_lon
            })

    if nearest_station is None:
        raise ValueError("No valid stations available.")

    return {
        "nearest_station": str(nearest_station["station_name"]),
        "distance_km": round(nearest_distance, 3),
        "nearby": nearest_distance <= 0.5,
        "station_latitude": float(nearest_station["latitude"]),
        "station_longitude": float(nearest_station["longitude"]),
        "nearby_stations": nearby_stations
    }

